def write_all(base):
    out = os.path.join(base, "foerder"); os.makedirs(out, exist_ok=True)
    texts = []
    for p in POSTS:
        spec = {"slug": p["slug"], "format": "portrait", "slides": p["slides"]}
        json.dump(spec, open(os.path.join(out, p["slug"] + ".json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        texts.append({k: p[k] for k in ("slug", "date", "hook", "title", "link", "tags", "body")})
    json.dump(texts, open(os.path.join(out, "texte.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(len(POSTS), "specs ->", out)


if __name__ == "__main__":
    write_all(os.path.dirname(os.path.abspath(__file__)))
